"""Build a single-module Cloudflare Worker that serves the static site in ./website.

Why: the site runs on the Cloudflare Worker "red-wave-f642". Cloudflare's usual
static-asset upload needs a one-time upload token in the Authorization header,
which the cloud session's credential proxy overwrites. Embedding the files in
the Worker code lets the site be published with the API token alone.

Behaviour matches Cloudflare's default static-asset handling
(html_handling "auto-trailing-slash", not_found_handling "none"):
  /page            -> 307 to /page/   (when /page/index.html exists)
  /page/index.html -> 307 to /page/
  /page/           -> serves /page/index.html
  unknown path     -> 404
Internal notes files (*.txt other than robots.txt) are not published.

Usage: python3 tools/build_worker.py website out/worker.js
"""
import base64, hashlib, json, os, sys

TYPES = {".html": "text/html; charset=utf-8", ".txt": "text/plain; charset=utf-8",
         ".xml": "application/xml; charset=utf-8", ".png": "image/png",
         ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".svg": "image/svg+xml",
         ".ico": "image/x-icon", ".webp": "image/webp", ".css": "text/css; charset=utf-8",
         ".js": "text/javascript; charset=utf-8", ".json": "application/json; charset=utf-8"}
TEXT = {".html", ".txt", ".xml", ".svg", ".css", ".js", ".json"}
SKIP = {"READ-THIS-FIRST.txt", "SEO-CHANGES.txt"}

def build(src, out):
    files = {}
    for root, _, names in os.walk(src):
        for n in sorted(names):
            if n in SKIP: continue
            p = os.path.join(root, n); ext = os.path.splitext(n)[1].lower()
            if ext not in TYPES: raise SystemExit(f"unknown file type: {p}")
            b = open(p, "rb").read()
            key = "/" + os.path.relpath(p, src).replace(os.sep, "/")
            e = {"type": TYPES[ext], "etag": '"' + hashlib.sha256(b).hexdigest()[:32] + '"'}
            if ext in TEXT: e["text"] = b.decode("utf-8")
            else: e["b64"] = base64.b64encode(b).decode()
            files[key] = e
    js = """// Generated by tools/build_worker.py - do not edit by hand.
const FILES = %s;
const BYTES = new Map();
function bytesOf(key) {
  let b = BYTES.get(key);
  if (!b) {
    const f = FILES[key];
    b = f.text !== undefined ? new TextEncoder().encode(f.text)
                             : Uint8Array.from(atob(f.b64), (c) => c.charCodeAt(0));
    BYTES.set(key, b);
  }
  return b;
}
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== "GET" && request.method !== "HEAD")
      return new Response("Method Not Allowed", { status: 405, headers: { Allow: "GET, HEAD" } });
    let path;
    try { path = decodeURIComponent(url.pathname); } catch { path = url.pathname; }
    const redirect = (to) => new Response(null, { status: 307, headers: { Location: url.origin + encodeURI(to) + url.search } });
    if (path.endsWith("/index.html")) {
      const dir = path.slice(0, -"index.html".length);
      if (FILES[dir + "index.html"]) return redirect(dir);
    }
    if (!path.endsWith("/") && !FILES[path] && FILES[path + "/index.html"]) return redirect(path + "/");
    const key = path.endsWith("/") ? path + "index.html" : path;
    const f = FILES[key];
    if (!f) return new Response("Not Found", { status: 404, headers: { "content-type": "text/plain; charset=utf-8" } });
    const headers = { "content-type": f.type, "cache-control": "public, max-age=0, must-revalidate", "etag": f.etag };
    if (request.headers.get("if-none-match") === f.etag) return new Response(null, { status: 304, headers });
    return new Response(request.method === "HEAD" ? null : bytesOf(key), { status: 200, headers });
  },
};
""" % json.dumps(files, ensure_ascii=False, indent=0)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    open(out, "w", encoding="utf-8").write(js)
    print(f"built {out}: {len(files)} files, {os.path.getsize(out)/1024:.0f} KB")
    return files

if __name__ == "__main__":
    build(sys.argv[1], sys.argv[2])
